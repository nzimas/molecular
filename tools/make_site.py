"""Molecular's website: each page's body in site/ wrapped in the frame (the menu, the footer) into docs/, the
GitHub Pages folder. Usage: make_site.py"""
import hashlib, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
PAGES = [  # file, menu label, title
    ("index.html", "Home", "Molecular — a firmware for the Sonicake Pocket Master"),
    ("install.html", "Install", "Install Molecular"),
    ("manual.html", "Manual", "Molecular — manual"),
    ("projects.html", "Other projects", "Other projects — Molecular"),
]
SRC = {"index.html": "home.html"}
DESC = ("Molecular: a firmware for the Sonicake Pocket Master for the discovery of sound -- electroacoustic, "
        "acousmatic and experimental music. A molecule of an FM generator and effect atoms, in motion.")
DONATE = '''<form class="donate %s" action="https://www.paypal.com/cgi-bin/webscr" method="post" target="_top">
      <input type="hidden" name="cmd" value="_xclick">
      <input type="hidden" name="business" value="nzimas.lv@gmail.com">
      <input type="hidden" name="item_name" value="Support Molecular">
      <input type="hidden" name="currency_code" value="EUR">
      <input type="image" src="https://www.paypalobjects.com/en_US/i/btn/btn_donateCC_LG.gif" name="submit"
             title="PayPal - The safer, easier way to pay online!" alt="Donate with PayPal button">
    </form>'''


def stamp(path):
    return hashlib.sha1(open(os.path.join(ROOT, "docs", path), "rb").read()).hexdigest()[:10]


def page(name, title, body, scripts):
    css = stamp("css/site.css")
    nav = "\n".join('      <a href="%s"%s>%s</a>' % ("./" if f == "index.html" else f,
                                                    ' aria-current="page"' if f == name else "", label)
                    for f, label, _ in PAGES)
    js = "".join('\n<script src="js/%s?v=%s"></script>' % (s, stamp("js/" + s)) for s in scripts + ["menu.js"])
    return f'''<!doctype html>
<!-- SPDX-License-Identifier: MIT -- Molecular website (generated by tools/make_site.py from site/) -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{DESC}">
<link rel="icon" href="assets/mark.svg" type="image/svg+xml">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="css/site.css?v={css}">
</head>
<body>
<div class="layout">
  <aside class="side">
    <div class="top">
      <a class="brand" href="./"><img src="assets/mark.svg" alt="">MOLECULAR</a>
      <button class="menu-btn" type="button" aria-label="Menu" aria-controls="site-nav" aria-expanded="false"><span></span><span></span><span></span></button>
    </div>
    <div class="layers" aria-hidden="true"><span></span><span></span><span></span><span></span><span></span><span></span><span></span></div>
    <nav id="site-nav" aria-label="Site">
      <button class="menu-close" type="button" aria-label="Close the menu">&times;</button>
{nav}
      <a href="https://github.com/nzimas/molecular">GitHub</a>
    </nav>
    <div class="menu-shade" hidden></div>
    {DONATE % "donate-side"}
  </aside>
  <div class="content">
    <main>
{body}
    </main>
    <footer>
      <p>Molecular is by Nuno Zimas. Firmware and installer: GPL-3.0. Website and logo: MIT.
        <a href="https://github.com/nzimas/molecular">Source on GitHub</a>.</p>
      <p>Sonicake and Pocket Master are trademarks of their owner, used only to say which device Molecular runs on.
        Molecular is not made, endorsed or supported by Sonicake.</p>
      {DONATE % "donate-foot"}
    </footer>
  </div>
</div>{js}
</body>
</html>
'''


def main():
    scripts = {"install.html": ["pmota.js", "install.js"]}
    for f, _, title in PAGES:
        body = open(os.path.join(ROOT, "site", SRC.get(f, f))).read().rstrip()
        open(os.path.join(ROOT, "docs", f), "w").write(page(f, title, body, scripts.get(f, [])))
    open(os.path.join(ROOT, "docs", ".nojekyll"), "w").close()
    print("wrote", ", ".join(f for f, _, _ in PAGES), "in docs/")


if __name__ == "__main__":
    main()
