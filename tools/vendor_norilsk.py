"""Copies Norilsk's effects (rack.c, the same author, GPL-3.0-only) into core/vendor/norilsk/effects.c, unchanged:
from its effect list (enum RM_*) to the end of rm_size, without its master REVERB include and its effect slots'
constants. Run from anywhere: python3 -I tools/vendor_norilsk.py [path to Norilsk's rack.c]"""
import os
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "norilsk", "firmware", "src", "rack.c")   # (a Norilsk checkout beside this one)
out = os.path.join(here, "..", "core", "vendor", "norilsk", "effects.c")

lines = open(src).read().split("\n")
start = next(i for i, l in enumerate(lines) if l.startswith("enum { RM_FLT"))
size = next(i for i, l in enumerate(lines) if l.startswith("static uint32_t rm_size"))
end = next(i for i in range(size, len(lines)) if lines[i] == "}") + 1
skip0 = next(i for i in range(start, end) if "REVERB --- */" in lines[i])
skip1 = next(i for i in range(skip0, end) if lines[i].startswith("/* ====="))
body = lines[start:skip0] + lines[skip1:end]

try:
    rev = subprocess.run(["git", "-C", os.path.dirname(src), "log", "-1", "--format=%h %ad", "--date=short"],
                         capture_output=True, text=True).stdout.strip()
except OSError:
    rev = "unknown"
head = [
    "/* SPDX-License-Identifier: GPL-3.0-only",
    " * Norilsk's effects, copied unchanged from its firmware/src/rack.c (commit %s) by tools/vendor_norilsk.py:" % rev,
    " * lines %d .. %d and %d .. %d of that file (its master REVERB include and effect slots' constants left out)." % (
        start + 1, skip0, skip1 + 1, end),
    " * Molecular's fx.c runs them as atoms. Do not edit: change Norilsk and copy again. */",
    "",
]
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("\n".join(head + body) + "\n")
print("%s: %d lines" % (os.path.relpath(out), len(body)))

# the one table Norilsk's effects read that Tonitor's tables lack (Norilsk's tools/gen_tables.py, the same formula)
import math
tab = os.path.join(os.path.dirname(out), "tables.h")
hann = [int(round(32767 * 0.5 * (1 - math.cos(2 * math.pi * i / 256)))) for i in range(257)]
rows = [", ".join(str(v) for v in hann[i:i + 16]) for i in range(0, 257, 16)]
open(tab, "w").write("/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/vendor_norilsk.py: Norilsk's HANN "
                     "(its tools/gen_tables.py), a Hann window in 257 points, Q15. */\n"
                     "static const int16_t HANN[257] = {\n    " + ",\n    ".join(rows) + "};\n")
print("%s: HANN" % os.path.relpath(tab))
